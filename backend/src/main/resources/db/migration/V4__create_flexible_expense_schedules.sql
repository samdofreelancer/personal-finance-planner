CREATE TABLE expense_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL
);

CREATE TABLE expense_amount_changes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    expense_category_id BIGINT NOT NULL REFERENCES expense_categories(id) ON DELETE CASCADE,
    effective_month DATE NOT NULL,
    amount BIGINT NOT NULL CHECK (amount >= 0),
    CONSTRAINT uk_expense_change_month UNIQUE (expense_category_id, effective_month),
    CONSTRAINT ck_expense_effective_month_start CHECK (EXTRACT(DAY FROM effective_month) = 1)
);

CREATE INDEX idx_expense_changes_category_month
    ON expense_amount_changes(expense_category_id, effective_month);

