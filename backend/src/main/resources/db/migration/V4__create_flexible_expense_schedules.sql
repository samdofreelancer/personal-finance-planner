WITH legacy AS (
    SELECT living, child_through_2026, child_q1_2027, child_from_apr_2027,
           rent_through_jan_2027, rent_from_feb_2027
    FROM assumptions ORDER BY id LIMIT 1
), amounts AS (
    SELECT 'Sinh hoạt phí' AS name, DATE '2026-11-01' AS effective_month, living AS amount FROM legacy
    UNION ALL SELECT 'Quỹ nuôi con', DATE '2026-11-01', child_through_2026 FROM legacy
    UNION ALL SELECT 'Quỹ nuôi con', DATE '2027-01-01', child_q1_2027 FROM legacy
    UNION ALL SELECT 'Quỹ nuôi con', DATE '2027-04-01', child_from_apr_2027 FROM legacy
    UNION ALL SELECT 'Tiền nhà', DATE '2026-11-01', rent_through_jan_2027 FROM legacy
    UNION ALL SELECT 'Tiền nhà', DATE '2027-02-01', rent_from_feb_2027 FROM legacy
)
INSERT INTO expense_amount_changes (expense_category_id, effective_month, amount)
SELECT category.id, amounts.effective_month, amounts.amount
FROM amounts JOIN expense_categories category ON category.name = amounts.name;

