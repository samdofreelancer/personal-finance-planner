CREATE TABLE income_amount_changes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assumption_id BIGINT NOT NULL REFERENCES assumptions(id) ON DELETE CASCADE,
    effective_month DATE NOT NULL,
    amount BIGINT NOT NULL CHECK (amount >= 0),
    CONSTRAINT uk_income_change_month UNIQUE (assumption_id, effective_month),
    CONSTRAINT ck_income_effective_month_start CHECK (EXTRACT(DAY FROM effective_month) = 1)
);

CREATE INDEX idx_income_changes_assumption_month
    ON income_amount_changes(assumption_id, effective_month);

INSERT INTO income_amount_changes (assumption_id, effective_month, amount)
SELECT id, DATE '2026-11-01', base_salary
FROM assumptions;

WITH RECURSIVE raise_factors (assumption_id, raise_year, factor) AS (
    SELECT a.id AS assumption_id,
           2027 AS raise_year,
           CAST(1 AS DECIMAL(30, 12)) + CAST(COALESCE(r.raise_rate, 0) AS DECIMAL(30, 12)) AS factor
    FROM assumptions a
    LEFT JOIN salary_raise_rates r ON r.assumption_id = a.id AND r.raise_year = 2027
    UNION ALL
    SELECT f.assumption_id,
           f.raise_year + 1,
           f.factor * (CAST(1 AS DECIMAL(30, 12)) + CAST(COALESCE(r.raise_rate, 0) AS DECIMAL(30, 12)))
    FROM raise_factors f
    LEFT JOIN salary_raise_rates r ON r.assumption_id = f.assumption_id AND r.raise_year = f.raise_year + 1
    WHERE f.raise_year < 2032
)
INSERT INTO income_amount_changes (assumption_id, effective_month, amount)
SELECT f.assumption_id,
       CAST(CAST(f.raise_year AS VARCHAR) || '-04-01' AS DATE),
       CAST(ROUND(a.base_salary * f.factor, 0) AS BIGINT)
FROM raise_factors f
JOIN assumptions a ON a.id = f.assumption_id;

DROP TABLE salary_raise_rates;
ALTER TABLE assumptions DROP COLUMN base_salary;
