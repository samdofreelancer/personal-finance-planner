CREATE TABLE loans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    opening_principal BIGINT NOT NULL CHECK (opening_principal >= 0),
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL
);

CREATE TABLE loan_repayments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loan_id BIGINT NOT NULL REFERENCES loans(id) ON DELETE CASCADE,
    due_date DATE NOT NULL,
    principal_amount BIGINT NOT NULL CHECK (principal_amount >= 0),
    interest_amount BIGINT NOT NULL CHECK (interest_amount >= 0)
);

CREATE INDEX idx_loan_repayments_loan_due_date ON loan_repayments(loan_id, due_date);

-- Preserve the former single-loan forecast for existing installations.
WITH legacy AS (
    SELECT loan_principal, fixed_payment, nov_interest, dec_interest, payoff_interest
    FROM assumptions
    ORDER BY id
    LIMIT 1
), created_loan AS (
    INSERT INTO loans (name, opening_principal, created_at, updated_at)
    SELECT 'Khoản vay hiện tại', loan_principal, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
    FROM legacy
    WHERE loan_principal > 0
    RETURNING id
), payments AS (
    SELECT id AS loan_id, DATE '2026-11-30' AS due_date,
           LEAST(loan_principal, GREATEST(0, fixed_payment - nov_interest)) AS principal_amount,
           nov_interest AS interest_amount
    FROM created_loan CROSS JOIN legacy
    UNION ALL
    SELECT id, DATE '2026-12-31',
           LEAST(GREATEST(0, loan_principal - LEAST(loan_principal, GREATEST(0, fixed_payment - nov_interest))),
                 GREATEST(0, fixed_payment - dec_interest)),
           dec_interest
    FROM created_loan CROSS JOIN legacy
    UNION ALL
    SELECT id, DATE '2027-01-31',
           GREATEST(0, loan_principal
               - LEAST(loan_principal, GREATEST(0, fixed_payment - nov_interest))
               - LEAST(GREATEST(0, loan_principal - LEAST(loan_principal, GREATEST(0, fixed_payment - nov_interest))),
                       GREATEST(0, fixed_payment - dec_interest))),
           COALESCE(payoff_interest, 0)
    FROM created_loan CROSS JOIN legacy
)
INSERT INTO loan_repayments (loan_id, due_date, principal_amount, interest_amount)
SELECT loan_id, due_date, principal_amount, interest_amount FROM payments;
