CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT ck_users_normalized_email CHECK (email = LOWER(email))
);

CREATE TABLE households (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    initial_household BOOLEAN NOT NULL DEFAULT FALSE,
    initial_household_key SMALLINT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_households_initial_key UNIQUE (initial_household_key),
    CONSTRAINT ck_households_initial_key CHECK (
        initial_household_key IS NULL OR (initial_household = TRUE AND initial_household_key = 1)
    )
);

