CREATE TABLE household_members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    household_id BIGINT NOT NULL REFERENCES households(id),
    user_id BIGINT NOT NULL REFERENCES users(id),
    role VARCHAR(16) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_household_members_user UNIQUE (user_id),
    CONSTRAINT ck_household_members_role CHECK (role IN ('OWNER', 'MEMBER'))
);

CREATE INDEX idx_household_members_household ON household_members(household_id);

CREATE TABLE household_invitations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    household_id BIGINT NOT NULL REFERENCES households(id),
    created_by_user_id BIGINT NOT NULL REFERENCES users(id),
    token_hash VARCHAR(64) NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked_at TIMESTAMP WITH TIME ZONE,
    consumed_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uk_household_invitations_token_hash UNIQUE (token_hash)
);

CREATE INDEX idx_household_invitations_household ON household_invitations(household_id);

